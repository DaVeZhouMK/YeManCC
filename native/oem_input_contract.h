// ROG is a machine family; Armoury Crate/SE are separately versioned writers.
// Never infer frontend identity just from hardware vendor or process/window name.
enum class Frontend { Unknown, MsiCenterM, AsusArmouryCrateSE, AsusArmouryCrate, LenovoLegionSpace };
inline Vendor frontendVendor(Frontend f) {
    switch(f) {
    case Frontend::MsiCenterM:return Vendor::Msi;
    case Frontend::AsusArmouryCrateSE: case Frontend::AsusArmouryCrate:return Vendor::AsusRog;
    case Frontend::LenovoLegionSpace:return Vendor::Lenovo;
    default:return Vendor::Unknown;
    }
}
enum class PolicyValue { Unknown, Automatic, NativeGamepad, VirtualCaptureCompatible };
struct Identification {
    Vendor machineVendor=Vendor::Unknown;
    Frontend frontend=Frontend::Unknown;
    bool machineVerified=false, installedComponentsVerified=false;
    std::string capabilityBinding; // Stable adapter identity; not a client label.
};
inline constexpr uint32_t fieldButtons=1u<<0,fieldDpad=1u<<1,fieldLeftStick=1u<<2,
    fieldRightStick=1u<<3,fieldTriggers=1u<<4;
inline constexpr uint32_t fullGamepadFields=fieldButtons|fieldDpad|fieldLeftStick|fieldRightStick|fieldTriggers;
inline bool digestText(std::string_view s) {
    if(s.size()!=64)return false;
    for(char c:s)if(!((c>='0'&&c<='9')||(c>='a'&&c<='f')||(c>='A'&&c<='F')))return false;
    return true;
}
struct InputContract {
    Owner owner;
    Identification identity;
    Capability capability;
    bool userAuthorized=false;
    Intent intent=Intent::VirtualCapture;
    // These are resolved by the family adapter, not global UI mode numbers.
    PhysicalRoute route;
    std::string physicalSource, virtualTarget, persona;
    uint64_t sourceGeneration=0, virtualTargetEpoch=0;
    bool isolationRequired=true;
    std::string hostRunId;
    uint32_t requiredFields=fullGamepadFields;
};
inline bool boundedIdentity(std::string_view s) {
    if(s.empty() || s.size()>512) return false;
    for(unsigned char c:s) if(c<32 || c==127) return false;
    return true;
}
enum class Admission { Accepted, Unauthorized, InvalidOwner, Unsupported, IdentityMismatch, InvalidSource };
inline Admission admit(const InputContract& c) {
    if(!c.userAuthorized) return Admission::Unauthorized;
    if(!validOwner(c.owner) || !validIntent(c.intent)) return Admission::InvalidOwner;
    if(!c.capability.captureCapabilityVerified || !c.route.supported() ||
       !boundedIdentity(c.capability.binding)) return Admission::Unsupported;
    if(!c.identity.machineVerified || !c.identity.installedComponentsVerified ||
       c.identity.machineVendor!=c.capability.vendor ||
       frontendVendor(c.identity.frontend)!=c.capability.vendor ||
       c.identity.capabilityBinding!=c.capability.binding || c.route.vendor!=c.capability.vendor ||
       !(c.route==(c.intent==Intent::VirtualCapture?c.capability.virtualRoute:c.capability.nativeRoute)))
        return Admission::IdentityMismatch;
    if(!boundedIdentity(c.physicalSource) || !c.sourceGeneration) return Admission::InvalidSource;
    if(c.intent==Intent::VirtualCapture && (!boundedIdentity(c.virtualTarget) ||
       !boundedIdentity(c.persona) || !boundedIdentity(c.hostRunId) || c.virtualTarget==c.physicalSource ||
       !c.virtualTargetEpoch || !c.requiredFields || (c.requiredFields&~fullGamepadFields)))
        return Admission::InvalidSource;
    return Admission::Accepted;
}
// All proofs below are generated by trusted in-process samplers / the independent
// observer, never accepted from a settings.write or arbitrary frontend IPC body.
struct ProofToken {
    Owner owner;
    std::string physicalSource;
    uint64_t sourceGeneration=0;
};
inline bool matches(const InputContract& c,const ProofToken& p) {
    return c.owner==p.owner && c.physicalSource==p.physicalSource &&
        c.sourceGeneration==p.sourceGeneration;
}
inline bool fresh(uint64_t tick,uint64_t now,uint64_t maxAge) {
    return tick!=0 && now>=tick && now-tick<=maxAge;
}
enum class ModeWitness { Unknown, FirmwareReadback, PhysicalSourceIdentity };
struct ModeProof {
    ProofToken token;
    ModeWitness witness=ModeWitness::Unknown;
    PhysicalRoute observedRoute;
    bool physicalIdentityVerified=false;
    uint64_t tick=0;
    HardwareState state=HardwareState::Unknown;
    TransitionOrigin origin=TransitionOrigin::Unknown;
};
struct CaptureProof {
    ProofToken token;
    bool readSucceeded=false, sourceIsPhysical=false, nonNeutral=false;
    uint64_t tick=0, sampleSequence=0;
    bool canonicalSourceBound=false;
    uint32_t availableFields=0;
    std::string normalizedInputHash;
};
enum class IsolationWitness { Unknown, IndependentSourceAccessDenied };
struct IsolationProof {
    ProofToken token;
    bool externalVisibilityVerified=false, physicalHidden=false, ownerCanCapture=false;
    bool externalNonNeutralObserved=false;
    uint64_t tick=0;
    IsolationWitness witness=IsolationWitness::Unknown;
};
struct SubmitProof {
    ProofToken token;
    std::string virtualTarget, persona;
    uint64_t virtualTargetEpoch=0, tick=0, sourceSampleSequence=0, reportSequence=0;
    bool effectiveTargetMatches=false, targetPresent=false, hostAccepted=false;
    // Distinct receipt: an accepted neutral report cannot prove non-neutral output.
    bool nonNeutralReportSubmitted=false, mappedStimulusExpected=false;
    bool frameBuilt=false, backendSubmitted=false, backendReceiptVerified=false;
    std::string hostRunId, sourceNormalizedInputHash, submittedFrameHash;
};
struct PolicyProof {
    Owner owner;
    std::string capabilityBinding;
    PolicyValue readback=PolicyValue::Unknown;
    bool exactReadback=false;
    uint64_t tick=0;
};
enum class ConsumerKind { Unknown, IndependentVirtualReader, Steam, Game };
struct ConsumerProof {
    Owner owner;
    std::string virtualTarget, hostRunId;
    uint64_t virtualTargetEpoch=0, reportSequence=0, tick=0;
    ConsumerKind kind=ConsumerKind::Unknown;
    bool targetIdentityVerified=false, stimulusCorrelationVerified=false, nonNeutralObserved=false;
};
struct ChainProofs { PolicyProof policy; ModeProof mode; CaptureProof capture; IsolationProof isolation; SubmitProof submit; ConsumerProof consumer; };
enum class ChainStage {
    InvalidContract, StaleEvidence, PolicyUnknown, PolicyDeviation, ModeUnknown,
    ModeDeviation, ProtectedPhysicalChoice, CaptureUnknown, IsolationUnknown, IsolationLeak, SubmitUnknown, StimulusNotSubmitted,
    ReadyForStimulus, StimulusSubmitted, ExternalReadConfirmedWindow, ConsumerConfirmedWindow
};
struct ChainResult {
    ChainStage stage=ChainStage::InvalidContract;
    bool policyVerified=false, hardwareModeWitnessed=false, captureVerified=false;
    bool isolationVerified=false, submitVerified=false, nonNeutralCorrelated=false;
    // Game-consumption proof requires a separately correlated external receipt;
    // no result guarantees lasting stability. Neutral is never "unaffected/no leak".
    bool gameConsumptionProven=false, lastingStabilityProven=false, externalReadProven=false;
    bool requiresUserAction=false, existingTargetMustNotBeRebuilt=true;
};
inline const char* stageName(ChainStage s) {
    switch(s) {
    case ChainStage::InvalidContract:return "invalid-contract";
    case ChainStage::StaleEvidence:return "stale-evidence";
    case ChainStage::PolicyUnknown:return "policy-unknown";
    case ChainStage::PolicyDeviation:return "policy-deviation";
    case ChainStage::ModeUnknown:return "mode-unknown";
    case ChainStage::ModeDeviation:return "mode-deviation";
    case ChainStage::ProtectedPhysicalChoice:return "protected-physical-choice";
    case ChainStage::CaptureUnknown:return "capture-unknown";
    case ChainStage::IsolationUnknown:return "isolation-unknown";
    case ChainStage::IsolationLeak:return "isolation-leak";
    case ChainStage::SubmitUnknown:return "submit-unknown";
    case ChainStage::StimulusNotSubmitted:return "stimulus-not-submitted";
    case ChainStage::ReadyForStimulus:return "ready-for-stimulus";
    case ChainStage::StimulusSubmitted:return "stimulus-submitted";
    case ChainStage::ExternalReadConfirmedWindow:return "external-read-confirmed-window";
    case ChainStage::ConsumerConfirmedWindow:return "consumer-confirmed-window";
    }
    return "unknown";
}
// Capture/Host/consumer can be assessed independently while official policy or
// firmware mode remains unknown. This does not grant any config/mode write.
inline ChainResult assessSignal(const InputContract& c,const ChainProofs& p,uint64_t now) {
    ChainResult out;
    if(admit(c)!=Admission::Accepted || c.intent!=Intent::VirtualCapture) return out;
    if(!matches(c,p.capture.token) || !matches(c,p.submit.token) ||
       (c.isolationRequired && !matches(c,p.isolation.token))) {
        out.stage=ChainStage::StaleEvidence;return out;
    }
    if(!p.capture.readSucceeded || !p.capture.sourceIsPhysical || !p.capture.canonicalSourceBound ||
       (p.capture.availableFields&c.requiredFields)!=c.requiredFields || !digestText(p.capture.normalizedInputHash) || !p.capture.sampleSequence ||
       !fresh(p.capture.tick,now,250)) {out.stage=ChainStage::CaptureUnknown;return out;}
    out.captureVerified=true;
    if(c.isolationRequired) {
        if(p.isolation.externalNonNeutralObserved) {out.stage=ChainStage::IsolationLeak;return out;}
        if(p.isolation.witness!=IsolationWitness::IndependentSourceAccessDenied ||
           !p.isolation.externalVisibilityVerified || !p.isolation.physicalHidden ||
           !p.isolation.ownerCanCapture || !fresh(p.isolation.tick,now,2000)) {
            out.stage=ChainStage::IsolationUnknown;return out;
        }
        out.isolationVerified=true;
    }
    if(p.submit.virtualTarget!=c.virtualTarget || p.submit.virtualTargetEpoch!=c.virtualTargetEpoch ||
       p.submit.persona!=c.persona || !p.submit.targetPresent || !p.submit.effectiveTargetMatches ||
       !p.submit.hostAccepted || !p.submit.frameBuilt || !p.submit.backendSubmitted || !p.submit.backendReceiptVerified ||
       p.submit.hostRunId!=c.hostRunId || !digestText(p.submit.submittedFrameHash) ||
       p.submit.sourceNormalizedInputHash!=p.capture.normalizedInputHash || !p.submit.reportSequence ||
       p.submit.sourceSampleSequence!=p.capture.sampleSequence || p.submit.tick<p.capture.tick ||
       !fresh(p.submit.tick,now,250)) {out.stage=ChainStage::SubmitUnknown;return out;}
    out.submitVerified=true;
    if(p.capture.nonNeutral && p.submit.mappedStimulusExpected && !p.submit.nonNeutralReportSubmitted) {
        out.stage=ChainStage::StimulusNotSubmitted;return out;
    }
    out.nonNeutralCorrelated=p.capture.nonNeutral && p.submit.mappedStimulusExpected && p.submit.nonNeutralReportSubmitted;
    out.stage=out.nonNeutralCorrelated?ChainStage::StimulusSubmitted:ChainStage::ReadyForStimulus;
    const auto& external=p.consumer;
    if(out.nonNeutralCorrelated && external.owner==c.owner && external.virtualTarget==c.virtualTarget &&
       external.hostRunId==c.hostRunId && external.virtualTargetEpoch==c.virtualTargetEpoch &&
       external.reportSequence==p.submit.reportSequence && external.tick>=p.submit.tick &&
       fresh(external.tick,now,2000) && external.targetIdentityVerified &&
       external.stimulusCorrelationVerified && external.nonNeutralObserved) {
        if(external.kind==ConsumerKind::IndependentVirtualReader) {
            out.externalReadProven=true;out.stage=ChainStage::ExternalReadConfirmedWindow;
        } else if(external.kind==ConsumerKind::Steam || external.kind==ConsumerKind::Game) {
            out.externalReadProven=true;out.gameConsumptionProven=true;out.stage=ChainStage::ConsumerConfirmedWindow;
        }
    }
    return out;
}

inline ChainResult evaluate(const InputContract& c,const ChainProofs& p,uint64_t now) {
    ChainResult out;
    if(admit(c)!=Admission::Accepted || c.intent!=Intent::VirtualCapture) return out;
    // These freshness limits are evidence admission, NOT device-write timers.
    if(!(p.policy.owner==c.owner) || p.policy.capabilityBinding!=c.capability.binding ||
       !fresh(p.policy.tick,now,2000) || !matches(c,p.mode.token) ||
       !matches(c,p.capture.token) || !matches(c,p.submit.token) ||
       (c.isolationRequired && !matches(c,p.isolation.token))) {
        out.stage=ChainStage::StaleEvidence;return out;
    }
    if(!p.policy.exactReadback || p.policy.readback==PolicyValue::Unknown) {out.stage=ChainStage::PolicyUnknown;return out;}
    if(p.policy.readback!=PolicyValue::VirtualCaptureCompatible) {out.stage=ChainStage::PolicyDeviation;return out;}
    out.policyVerified=true;
    if(!p.mode.physicalIdentityVerified || p.mode.witness==ModeWitness::Unknown ||
       !fresh(p.mode.tick,now,2000)) {out.stage=ChainStage::ModeUnknown;return out;}
    const bool physicalCause=p.mode.origin==TransitionOrigin::ExplicitUserIntent || p.mode.origin==TransitionOrigin::PhysicalTopology ||
        p.mode.origin==TransitionOrigin::PhysicalSwitch || p.mode.origin==TransitionOrigin::OfficialShortcut;
    if(p.mode.state==HardwareState::DetachedDualInput || p.mode.state==HardwareState::FpsHardware ||
       p.mode.state==HardwareState::ControllerOff || (physicalCause && !(p.mode.observedRoute==c.route))) {
        out.stage=ChainStage::ProtectedPhysicalChoice;out.requiresUserAction=true;return out;
    }
    if(p.mode.state==HardwareState::Unknown || !p.mode.observedRoute.supported()) {
        out.stage=ChainStage::ModeUnknown;return out;
    }
    if(!(p.mode.observedRoute==c.route)) {out.stage=ChainStage::ModeDeviation;return out;}
    out.hardwareModeWitnessed=true;
    auto signal=assessSignal(c,p,now);
    signal.policyVerified=out.policyVerified;
    signal.hardwareModeWitnessed=out.hardwareModeWitnessed;
    return signal;
}
// Backend extension point: inspect the four independent layers; mode writes are
// queued to the existing per-family worker. Implementations must never add a
// timer, stop services, re-enumerate virtual targets or trust firmware ACK alone.
struct ProviderObservation {
    Identification identity;
    PolicyValue desiredUserPreference=PolicyValue::Unknown;
    PolicyValue actualAutoPolicy=PolicyValue::Unknown;
    ModeProof actualHardwareMode;
    bool virtualOwnershipVerified=false;
};
struct ModeIntent { Owner owner; PhysicalRoute route; std::string evidenceReceipt; };
struct OemInputProvider {
    virtual ~OemInputProvider() = default;
    // Registry transactions are ONE backend (MSI), not a requirement that every
    // OEM expose registry settings. SDK/IPC providers own their equivalent leases.
    virtual Capability capability() const = 0;
    virtual Result acquirePolicy(const Request&) = 0;
    virtual Result releasePolicy(const Owner&) = 0;
    virtual Result recoverPolicy() = 0;
    virtual ProviderObservation inspect(const Owner&) = 0;
    // Submission ACK is only queue acceptance; caller must await mode+capture proof.
    virtual bool enqueueExistingModeWriter(const ModeIntent&) = 0;
};
class UnverifiedInputProvider final : public OemInputProvider {
    Frontend frontend_;
    static Result unsupported(){return {};}
public:
    explicit UnverifiedInputProvider(Frontend f):frontend_(f){}
    Capability capability() const override {Capability c;c.vendor=frontendVendor(frontend_);return c;}
    Result acquirePolicy(const Request&) override {return unsupported();}
    Result releasePolicy(const Owner&) override {return unsupported();}
    Result recoverPolicy() override {return unsupported();}
    ProviderObservation inspect(const Owner&) override {
        ProviderObservation o;o.identity.frontend=frontend_;return o;
    }
    bool enqueueExistingModeWriter(const ModeIntent&) override {return false;}
};
