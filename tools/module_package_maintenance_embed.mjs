import fs from 'node:fs';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const ps=fs.readFileSync(path.join(root,'native/module_package_maintenance.ps1'),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
if(ps.includes(')YMCCMODULEPKG"'))throw Error('delimiter collision');
// Keep the existing const-char pointer/static lifetime and the exact script.
// MSVC caps each literal token; mirror the Decky embedder's <=8KiB UTF-8
// complete-line chunks. Regenerate this header, then run --check before build.
const chunks=[];let chunk='';
for(const line of ps.match(/[^\n]*\n|[^\n]+$/g)||[]){
  if(Buffer.byteLength(line,'utf8')>8192)throw Error('Module maintenance source line exceeds literal chunk budget');
  if(Buffer.byteLength(chunk+line,'utf8')>8192){chunks.push(chunk);chunk='';}
  chunk+=line;
}
if(chunk||!chunks.length)chunks.push(chunk);
const literals=chunks.map(value=>'R"YMCCMODULEPKG('+value+')YMCCMODULEPKG"').join('\n');
const text='#pragma once\n// Generated by tools/module_package_maintenance_embed.mjs.\nnamespace ymcc::modulepackage {\ninline const char* maintenanceScript(){return '+literals+';}\n}\n';
const header=path.join(root,'native/module_package_maintenance_script.h');
if(process.argv.includes('--check')){if(fs.readFileSync(header,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('module source/header mismatch');}
else fs.writeFileSync(header,text);
