import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const mainRaw=fs.readFileSync(path.join(repo,'native/main.cpp'),'utf8');
const main=mainRaw.replaceAll('\r\n','\n');
const start='        // MSI_TRANSPORT_FAILURE_EVIDENCE_BEGIN';
const end='        // MSI_TRANSPORT_FAILURE_EVIDENCE_END';
const lo=main.indexOf(start),hi=main.indexOf(end,lo);
assert.ok(lo>=0 && hi>lo && main.indexOf(start,lo+start.length)<0,'One exact runtime evidence block');
const block=main.slice(lo+start.length,hi);
assert.match(block,/g_machineIdentity\.family == YmccFamily::MsiClaw/);
assert.match(block,/catch \(\.\.\.\)/);
const failureStart=main.lastIndexOf('    if (!read) {',lo);
assert.ok(failureStart>main.indexOf('static bool inputHostRequestPreparedLocked('),'Evidence is in actual transport failure branch');
assert.ok(lo<main.indexOf('        if (pipe) {',failureStart),'Evidence captured before pipe disconnect');
assert.ok(!/CancelIo|WaitFor|ReadFile|WriteFile|CreateProcess|modeSet|inputHostRequest|HidHide|SetupDi/.test(block),'Diagnostic block has no transport, mode or device operations');
const headerPath=path.join(repo,'native/msi_input_host_transport_evidence.h');
const header=fs.readFileSync(headerPath,'utf8');
const fixtureSource=fs.readFileSync(path.join(repo,'tools/msi_input_host_transport_evidence_selftest.cpp'),'utf8');
const baseStart=main.indexOf('static bool nativeLifecycleEventIsBase(const char* event) {');
const baseEnd=main.indexOf('\n}\n',baseStart)+3;
assert.ok(baseStart>0 && baseEnd>baseStart,'Actual default-event classifier extracted');
const baseClassifier=main.slice(baseStart,baseEnd);
const fixture=fixtureSource.replace('/* PRODUCTION_MSI_TRANSPORT_FAULT_BLOCK */',block)
    .replace('/* PRODUCTION_BASE_EVENT_CLASSIFIER */',baseClassifier);
const out=path.resolve(process.env.YMCC_MSI_TRANSPORT_EVIDENCE_OUT || 'G:/YeManCC-Work/Build/Validation/MSI-SD-Lifecycle-R6-20261013/transport-failure-evidence');
fs.mkdirSync(out,{recursive:true});
const cpp=path.join(out,'fixture.cpp'),exe=path.join(out,'fixture.exe'),batch=path.join(out,'compile.cmd');
fs.writeFileSync(cpp,fixture);
fs.writeFileSync(batch,'@echo off\r\ncall "C:\\Program Files (x86)\\Microsoft Visual Studio\\2022\\BuildTools\\VC\\Auxiliary\\Build\\vcvars64.bat" >nul\r\ncl /nologo /std:c++20 /utf-8 /EHsc /MT /O2 /I"'+path.join(repo,'deps/json')+'" /I"'+path.join(repo,'native')+'" "'+cpp+'" /Fo"'+path.join(out,'fixture.obj')+'" /Fe"'+exe+'"\r\nexit /b %errorlevel%\r\n');
const build=spawnSync('cmd.exe',['/d','/c',batch],{cwd:out,encoding:'utf8'});
fs.writeFileSync(path.join(out,'build.log'),(build.stdout||'')+(build.stderr||''));
if(build.status!==0)process.stdout.write((build.stdout||'')+(build.stderr||''));
assert.equal(build.status,0,'Offline evidence block compilation');
const run=spawnSync(exe,[],{cwd:out,encoding:'utf8'});
fs.writeFileSync(path.join(out,'stdout.txt'),run.stdout||'');fs.writeFileSync(path.join(out,'stderr.txt'),run.stderr||'');
assert.equal(run.status,0,(run.stdout||'')+(run.stderr||''));
const result=JSON.parse(run.stdout.trim());
const hash=s=>createHash('sha256').update(s).digest('hex');
assert.equal(fs.readFileSync(headerPath,'utf8'),header,'Bound header unchanged during test');
const current=fs.readFileSync(path.join(repo,'native/main.cpp'),'utf8').replaceAll('\r\n','\n');
assert.equal(current.slice(current.indexOf(start)+start.length,current.indexOf(end)),block,'Exact runtime block unchanged during test');
const currentBaseStart=current.indexOf('static bool nativeLifecycleEventIsBase(const char* event) {');
assert.equal(current.slice(currentBaseStart,current.indexOf('\n}\n',currentBaseStart)+3),baseClassifier,'Actual default-event classifier unchanged during test');
fs.writeFileSync(path.join(out,'verification-summary.json'),JSON.stringify({...result,exitCode:run.status,sourceStable:true,
    mainSha256:hash(mainRaw),runtimeBlockSha256:hash(block),baseClassifierSha256:hash(baseClassifier),headerSha256:hash(header),fixtureSha256:hash(fixture),
    productionLaunched:false,liveProbeLaunched:false,servicesOrRegistryChanged:false},null,2)+'\n');
process.stdout.write(run.stdout);
