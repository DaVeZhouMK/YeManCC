import fs from 'node:fs';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),file=path.join(root,'native/updater_hc_runtime_script.h');
const ps=fs.readFileSync(path.join(root,'native/updater_hc_runtime.ps1'),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
if(ps.includes(')YMCCHCRUNTIME"'))throw Error('delimiter collision');
// Keep each raw literal below MSVC's per-literal limit; adjacent literals preserve the exact script bytes.
const chunks=ps.match(/[\s\S]{1,4000}/gu)||[''];
const literals=chunks.map(chunk=>'R"YMCCHCRUNTIME('+chunk+')YMCCHCRUNTIME"').join('\n');
const text='#pragma once\n// Generated by tools/updater_hc_runtime_embed.mjs.\nnamespace ymcc::hcruntime {\ninline const char* script(){return\n'+literals+';}\n}\n';
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('HC runtime source/header mismatch');}else fs.writeFileSync(file,text);
