// Bind both binaries to the reviewed battery implementation, independently of package timestamps.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const directory='native/BatteryHost';
const inputs=fs.readdirSync(path.join(root,directory)).filter(n=>/\.(cs|csproj|json)$/.test(n)&&n!=='runtime-contract.json').map(n=>`${directory}/${n}`);
// Follow explicit source links so future catalog modules cannot fall outside the identity contract.
const project=fs.readFileSync(path.join(root,directory,'YeManBatteryHost.csproj'),'utf8');
for(const match of project.matchAll(/<Compile\s+Include="([^"]+)"/g)){
 const include=match[1];if(/[\$*?]/.test(include))throw Error('Battery contract requires a resolved literal Compile input: '+include);
 const full=path.resolve(root,directory,include.replaceAll('\\','/')),relative=path.relative(root,full).replaceAll('\\','/');
 if(relative==='..'||relative.startsWith('../')||path.isAbsolute(relative))throw Error('Battery source link leaves the repository');
 if(!inputs.includes(relative))inputs.push(relative);
}
inputs.push('native/battery_charge_client.h','native/secondary_display_client.h','tools/battery-charge-contract.mjs');
const hash=crypto.createHash('sha256');
for(const name of inputs.sort())hash.update(name+'\0'+fs.readFileSync(path.join(root,name),'utf8').replaceAll('\r\n','\n')+'\0');
const contract={schema:1,protocol:2,component:'YeManBatteryHost',implementation:'msi-cg3em-ap-unknown-v2',sourceId:hash.digest('hex')};
const generated={
 'native/BatteryHost/runtime-contract.json':JSON.stringify(contract,null,2)+'\n',
 'native/battery_host_contract.h':`// Generated by tools/battery-charge-contract.mjs. Do not edit.\n#pragma once\nnamespace ymcc::batterycharge {\ninline constexpr int kHostProtocol=${contract.protocol};\ninline constexpr const char* kHostSourceId="${contract.sourceId}";\ninline constexpr const char* kHostImplementation="${contract.implementation}";\n}\n`
};
for(const [name,text] of Object.entries(generated)){
 if(process.argv.includes('--check'))assert.equal(fs.readFileSync(path.join(root,name),'utf8').replaceAll('\r\n','\n'),text,`Stale battery contract: regenerate with node tools/battery-charge-contract.mjs (${name})`);
 else fs.writeFileSync(path.join(root,name),text);
}
console.log(`BATTERY_CONTRACT_OK: protocol=${contract.protocol} source=${contract.sourceId} implementation=${contract.implementation}`);
