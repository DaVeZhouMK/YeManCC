import fs from 'node:fs';import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const ps=fs.readFileSync(path.join(root,'native/update_install_recovery.ps1'),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
if(ps.includes(')YMCCRECOVERY"'))throw Error('delimiter collision');
// Keep each raw literal below MSVC's per-literal byte limit.
const chunks=[];let chunk='';
for(const line of ps.match(/[^\n]*\n|[^\n]+$/g)||[]){
  if(Buffer.byteLength(line,'utf8')>8192)throw Error('Recovery source line exceeds literal chunk budget');
  if(Buffer.byteLength(chunk+line,'utf8')>8192){chunks.push(chunk);chunk='';}
  chunk+=line;
}
if(chunk||!chunks.length)chunks.push(chunk);
const literals=chunks.map(value=>'R"YMCCRECOVERY('+value+')YMCCRECOVERY"').join('\n');
const text='#pragma once\n// Generated by tools/update_install_recovery_embed.mjs.\nnamespace ymcc::updaterecovery {\ninline const char* script(){return '+literals+';}\n}\n';
const file=path.join(root,'native/update_install_recovery_script.h');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('recovery source/header mismatch');}else fs.writeFileSync(file,text);
