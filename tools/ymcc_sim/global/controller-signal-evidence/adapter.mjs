export function deduplicateArtifactRows(rows){
  const unique=new Map();
  for(const row of rows){
    if(typeof row.path!=='string'||!path.win32.isAbsolute(row.path)||!/^[a-f0-9]{64}$/.test(row.sha256)||/[\0\r\n]/.test(row.path))throw Error('CONTROLLER_ARTIFACT_IDENTITY_INVALID');
    const normalized=path.win32.resolve(row.path),key=normalized.toLowerCase(),prior=unique.get(key);
    if(prior&&prior.sha256!==row.sha256)throw Error('CONTROLLER_ARTIFACT_PATH_HASH_CONFLICT:'+normalized);
    if(prior){if(!prior.origins.includes(row.origin))prior.origins.push(row.origin);}
    else unique.set(key,{path:normalized,sha256:row.sha256,origins:[row.origin]});
  }
  return [...unique.values()];
}
