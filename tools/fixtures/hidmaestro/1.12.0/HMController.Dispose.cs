	public void Dispose()
	{
		if (!_disposed)
		{
			try
			{
				SendReleaseFrames();
			}
			catch
			{
			}
			_disposed = true;
			try
			{
				_idleCts.Cancel();
			}
			catch
			{
			}
			try
			{
				_idleThread?.Join(TimeoutScale.Apply(500));
			}
			catch
			{
			}
			try
			{
				_outputCts.Cancel();
			}
			catch
			{
			}
			try
			{
				_outputThread?.Join(TimeoutScale.Apply(500));
			}
			catch
			{
			}
			try
			{
				SharedMemoryIO.UnregisterOutputPump(Index);
			}
			catch
			{
			}
			try
			{
				_outputCts.Dispose();
			}
			catch
			{
			}
			_context.OnControllerDisposing(this);
		}
	}
