"""Extract reviewed HC functions verbatim; refuse source drift or generated drift.

Only type bindings/base-class scaffolding differ. HID Write/IsConnected are the
terminal injection; no App, factory, UI, EC, serial, WMI or device Open is linked.
"""
import argparse
import hashlib
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SOURCE = ROOT / 'deps/handheldcompanion-runtime/source'
OUTPUT = ROOT / 'FanLab/LightSetter/DeviceCore/PinnedOneXHidV1.g.cs'
FILES = {
    'Devices/OneXAOKZOE.cs': 'DA6FF4ABE3BDF6D2879F6681921867EF10B62759D4DADC2EB0B18D12D7B39B3B',
    'Devices/IDevice.cs': 'FBAED1DFD329E3328376488B8EC70C3A7FDCF97D70DCB37F1525EE33AA169C20',
    'Devices/OneXPlayer/OneXPlayerX1Mini.cs': '2BCC0688AC0CB65091F29432A2351E00D724259778FFB3891AC9CA82A05852C0',
}


def function(text, name):
    match = re.search(r'^\s*(?:public|protected) [^\n]*\b' + name + r'\([^\n]*\)\s*\n\s*\{', text, re.M)
    if not match:
        raise RuntimeError('missing pinned function ' + name)
    # The reviewed methods have no braces in string literals. Preserve each
    # function's exact characters, including body whitespace, after LF decoding.
    start = match.start()
    while text[start] in '\r\n':
        start += 1
    pos = text.index('{', match.start())
    depth = 1
    end = pos + 1
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    return text[start:end]


def generate():
    texts = {}
    for path, expected in FILES.items():
        data = (SOURCE / path).read_bytes()
        actual = hashlib.sha256(data).hexdigest().upper()
        if actual != expected:
            raise RuntimeError(f'pinned HC source drift: {path}: {actual}')
        texts[path] = data.decode('utf-8-sig').replace('\r\n', '\n')
    base = ['BuildV1Command', 'SendV1Brightness', 'SendV1SolidColor', 'SendV1Rainbow']
    methods = [function(texts['Devices/OneXAOKZOE.cs'], name) for name in base]
    methods.append(function(texts['Devices/IDevice.cs'], 'WithReportID'))
    device = [function(texts['Devices/OneXPlayer/OneXPlayerX1Mini.cs'], name)
              for name in ['SetLedColor', 'SetLedBrightness']]
    generated = '''// <auto-generated> extract_pinned.py; source hashes in source-lock.json.
// HC function text is reused verbatim. Color and HidDevice are BCL/terminal aliases.
// Source attribution and extraction scope: SOURCE-NOTICE.md beside this file.
#nullable enable
using HidDevice = YeManCC.Lighting.ILightingHidTransport;
using Color = YeManCC.Lighting.RgbColor;
namespace YeManCC.Lighting;

internal abstract class PinnedOneXProtocol
{
    public abstract bool SetLedColor(Color mainColor, Color secondaryColor, LEDLevel level, int speed = 100);
    public abstract bool SetLedBrightness(int brightness);
'''
    generated += '\n\n'.join(methods) + '\n}\n\n'
    generated += '''internal sealed class PinnedX1MiniProtocol : PinnedOneXProtocol
{
    private readonly HidDevice hidDevice;
    private readonly LEDLevel DynamicLightingCapabilities = LEDLevel.SolidColor | LEDLevel.LEDPreset | LEDLevel.Rainbow;
    internal PinnedX1MiniProtocol(HidDevice transport) => hidDevice = transport;
'''
    generated += '\n\n'.join(device) + '\n}\n'
    lock = {'schema': 1, 'baselineId': 'HC-BINARY-BATCH12-20260831',
            'pinnedSource': str(SOURCE.relative_to(ROOT)).replace('\\', '/'),
            'files': FILES, 'functions': base + ['WithReportID', 'SetLedColor', 'SetLedBrightness'],
            'changes': ['HidDevice alias to terminal interface', 'Color alias to BCL RGB value',
                        'minimal base class and capability/transport constructor scaffolding'],
            'generatedSha256': hashlib.sha256(generated.encode()).hexdigest(),
            'physicalDeviceVerified': False}
    return generated, json.dumps(lock, indent=2) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, lock = generate()
    for path, contents in [(OUTPUT, generated), (HERE / 'source-lock.json', lock)]:
        if args.check:
            if path.read_text(encoding='utf-8-sig') != contents:
                raise RuntimeError('generated source drift: ' + str(path))
        else:
            path.write_text(contents, encoding='utf-8', newline='\n')
    print(json.dumps({'pinnedFiles': len(FILES), 'verbatimFunctions': 7, 'generatedVerified': args.check}))
