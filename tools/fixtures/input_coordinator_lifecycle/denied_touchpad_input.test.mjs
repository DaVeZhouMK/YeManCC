import assert from 'node:assert/strict';
import path from 'node:path';
import test from 'node:test';
import {bindDeniedTouchpadInput,deniedTouchpadInputSource} from './denied_touchpad_input.mjs';
import {bindCurrentTouchpadInputFixturePort} from '../../input_coordinator_current_compile_only.mjs';
import {getSupplementalAdapter} from '../../ymcc_sim/global/controller-coordinator-lifecycle/supplemental.mjs';
import {terminal26LocalNativeToolFiles} from '../../ymcc_sim/global/controller-coordinator-pipe/r3-terminal22-native-prepare.mjs';

const anchor='#include "screen_touchpads.h"',sample=`// preserved\r\n${anchor}\r\n// preserved\r\n`;
const oldCompiler='tools/input_coordinator_current_compile_only.mjs';
const oldProfile='tools/input_coordinator_terminal26_source_profile.mjs';

test('denied touchpad port keeps the existing generated bytes and evidence',()=>{
 const out=bindDeniedTouchpadInput(sample),[row]=out.substitutions;
 assert.equal(out.substitutions.length,1);
 assert.equal(row.beforeSha256,'20ffe4e8059c3580128fde56152fb0ba0dd4392f052e4154002332e5981e157e');
 assert.equal(row.afterSha256,'2edf747e057b7e41142185b5de28de643d3240bd3435d1d937c314696e8d0628');
 assert.equal(row.rejectOnly,true);
 assert.equal(row.sourceCaptureModified,false);
 assert(out.source.startsWith('// preserved\r\n#ifndef YMCC_SCREEN_NATIVE_INPUT_CANDIDATE\n'));
 assert(out.source.endsWith(anchor+'\r\n// preserved\r\n'));
 assert(out.source.includes('++::forbiddenIo;throw std::logic_error("unexpected-offline-touchpad-input-channel-reset")'));
});

test('denied touchpad port rejects a missing or ambiguous C++ anchor',()=>{
 for(const bad of ['unrelated',anchor+'\n'+anchor])assert.throws(()=>bindDeniedTouchpadInput(bad),/CURRENT_TOUCHPAD_INPUT_INCLUDE_REQUIRED/);
});

test('compile-only caller preserves no-op, profile validation and shared-power behavior',()=>{
 assert.deepEqual(bindCurrentTouchpadInputFixturePort(sample),{source:sample,substitutions:[]});
 assert.throws(()=>bindCurrentTouchpadInputFixturePort(sample,{nativeSourceProfile:'unknown'}),/TERMINAL26_UNKNOWN_NATIVE_SOURCE_PROFILE/);
 for(const options of [{sharedInputPower:true},{nativeSourceProfile:'current105-terminal26-current-capture-20261117a'}])
  assert.deepEqual(bindCurrentTouchpadInputFixturePort(sample,options),bindDeniedTouchpadInput(sample));
});

test('original directed managed routes pin only the touchpad leaf for this port',()=>{
 const names=['ps-exit-held-ownership-receipt','ps-exit-held-ownership-receipt:pair','prepare-rejection-cold',
  'gpd-expired-first-on-full-cycle','gpd-settled-first-on-full-cycle','wake-kept-source:GPD:expired-then-current'];
 for(const caseName of names){
  const adapter=getSupplementalAdapter({caseName,planning:true});
  assert.equal(adapter.id,'controller.coordinator-lifecycle');
  assert.equal(adapter.evidenceInputs.filter(file=>file===deniedTouchpadInputSource).length,1,caseName);
  assert(!adapter.evidenceInputs.includes(oldCompiler)&&!adapter.evidenceInputs.includes(oldProfile),caseName);
  assert.equal(adapter.cacheAcceptance,false);
 }
});

test('trusted compile-only tool inventory keeps the new dependency with its real owners',()=>{
 const primary=path.resolve(import.meta.dirname,'../../..'),captured=path.join(primary,'fixture-control-only-capture');
 for(const managedInputContract of ['current105-terminal26-sdk-lifetime-compact-v1','current105-terminal29-shared-input-power-v1']){
  const files=terminal26LocalNativeToolFiles({primaryRoot:primary,sourceRoot:captured,managedInputContract});
  for(const relative of [deniedTouchpadInputSource,oldCompiler,oldProfile]){
   assert.equal(files.filter(file=>file===path.join(primary,relative)).length,1);
   assert(!files.includes(path.join(captured,relative)));
  }
 }
});
