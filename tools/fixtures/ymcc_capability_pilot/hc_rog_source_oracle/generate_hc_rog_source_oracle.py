#!/usr/bin/env python3
"""Extract pinned HC declarations without rewriting a single method-body byte."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

PINS = {
    "Devices/ASUS/ROGAlly.cs": "04097428F3D62DE75F8160EB47398E1C61606F9D6681EB605D100B384814AA00",
    "Devices/ASUS/AsusACPI.cs": "C8186CEEEC817830D756FB5D78EAD44E7D6BB16A615A90F3358B85EC143BD34A",
    "Misc/FanProfile.cs": "A8C8921B324020940FAC42D4284C94F74139844B676D6D6BEB1ABB5FD1CCE8A5",
    "Misc/Profile.cs": "34A1F734D1C90C2D0A78DF102A306D185AD3DA128C61D3BF1ECC870BB58DC1E4",
}
INDEX_SHA256 = "9105B05655C280F99FFFFDB214C165955CED5EF3463719D681E7ABECF7E904D1"
BASELINE_ID = "HC-BINARY-BATCH12-20260831"
BASELINE_VERSION = "0.32.3.2"
ROG = "Devices/ASUS/ROGAlly.cs"
SELECTIONS = [
    (ROG, "defaultCPUFan", "private static byte[] defaultCPUFan =", False, False),
    (ROG, "defaultGPUFan", "private static byte[] defaultGPUFan =", False, False),
    (ROG, "ToAsusCurve(double[])", "private static byte[] ToAsusCurve(double[] fanSpeeds)", True, False),
    (ROG, "PowerProfileManager_Applied(PowerProfile, UpdateSource)", "public override void PowerProfileManager_Applied(PowerProfile profile, UpdateSource source)", True, False),
    (ROG, "SetFanControl(bool, int)", "public override void SetFanControl(bool enable, int mode = 0)", True, False),
    ("Devices/ASUS/AsusACPI.cs", "AsusFan", "public enum AsusFan", True, False),
    ("Misc/FanProfile.cs", "FanMode", "public enum FanMode", True, False),
    ("Misc/Profile.cs", "UpdateSource", "public enum UpdateSource", True, True),
]


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest().upper()


def extract(data: bytes, marker: str, block: bool, attribute: bool) -> tuple[int, int, bytes]:
    lines = data.splitlines(keepends=True)
    matches = [i for i, line in enumerate(lines) if line.decode("utf-8-sig").strip().startswith(marker)]
    if len(matches) != 1:
        raise ValueError(f"Expected one declaration: {marker}; found {len(matches)}")
    start = matches[0]
    end = start
    if block:
        # All inputs are pinned above; selected declarations have no braces in strings/comments.
        depth = 0
        opened = False
        for end in range(start, len(lines)):
            line = lines[end]
            if b"{" in line:
                opened = True
            depth += line.count(b"{") - line.count(b"}")
            if opened and depth == 0:
                break
        else:
            raise ValueError(f"Unclosed declaration: {marker}")
    if attribute:
        if lines[start - 1].strip() != b"[Flags]":
            raise ValueError("Pinned UpdateSource must retain [Flags]")
        start -= 1
    return start + 1, end + 1, b"".join(lines[start:end + 1])


def build(repo: Path) -> tuple[bytes, bytes]:
    dependency = repo / "deps/handheldcompanion-runtime"
    baseline = json.loads((dependency / "HC-BASELINE.json").read_text(encoding="utf-8-sig"))
    if (baseline["baselineId"], baseline["upstreamProjectVersion"]) != (BASELINE_ID, BASELINE_VERSION):
        raise ValueError("HC baseline identity changed; extraction refused")
    index_bytes = (dependency / "source-files.sha256").read_bytes()
    if sha256(index_bytes) != INDEX_SHA256 or baseline["sourceFilesIndexSha256"] != INDEX_SHA256:
        raise ValueError("HC frozen source index changed; extraction refused")
    index = {}
    for line in index_bytes.decode("utf-8-sig").splitlines():
        match = re.fullmatch(r"([0-9A-Fa-f]{64})\s+(.+)", line)
        if match:
            index[match[2].replace("\\", "/")] = match[1].upper()
    sources = {}
    for path, expected in PINS.items():
        data = (dependency / "source" / path).read_bytes()
        if sha256(data) != expected or index.get(path) != expected:
            raise ValueError(f"Frozen source/index hash mismatch: {path}")
        sources[path] = data

    generated = bytearray(
        b"// <auto-generated> Exact declarations extracted by generate_hc_rog_source_oracle.py.\n"
        b"// No HC constructor, device inheritance, factory, or native transport is included.\n"
        b"// See HcRogSourceOracle.provenance.json for hashes and inclusive source ranges.\n"
        b"// </auto-generated>\n#nullable disable\nusing System;\n\n"
        b"namespace Ymcc.CapabilityPilot.HcReference;\n\n"
        b"public sealed partial class HcRogSourceOracle : HcRogSourceOracleBase\n{\n"
    )
    ranges = []
    for selection_number, (path, symbol, marker, block, attribute) in enumerate(SELECTIONS):
        if selection_number == 5:
            generated.extend(b"}\n\n")
        first, last, snippet = extract(sources[path], marker, block, attribute)
        relative = f"deps/handheldcompanion-runtime/source/{path}"
        generated.extend(f'#line {first} "{relative}"\n'.encode("utf-8"))
        generated_first = len(generated.splitlines()) + 1
        generated.extend(snippet)
        generated_last = len(generated.splitlines())
        if not snippet.endswith(b"\n"):
            generated.extend(b"\n")
        generated.extend(b"#line default\n\n")
        ranges.append({
            "symbol": symbol,
            "sourcePath": relative,
            "sourceStartLine": first,
            "sourceEndLine": last,
            "sourceSha256": PINS[path],
            "excerptSha256": sha256(snippet),
            "generatedStartLine": generated_first,
            "generatedEndLine": generated_last,
            "verbatimIncludingLineEndings": True,
        })
    generated.extend(b"#nullable restore\n")
    result = bytes(generated)
    metadata = {
        "schemaVersion": 1,
        "baselineId": BASELINE_ID,
        "upstreamProjectVersion": BASELINE_VERSION,
        "sourceFilesIndexSha256": INDEX_SHA256,
        "generatorSha256": sha256(Path(__file__).read_bytes()),
        "generatedPath": "Generated/HcRogSourceOracle.g.cs",
        "generatedSha256": sha256(result),
        "captureBoundary": "AsusACPI.SetFanCurve arguments; no ACPI clamping, wire packing, device IO or HC factory",
        "editsToExtractedDeclarations": [],
        "scaffolding": [
            "Enclosing namespace and partial class replace the device class container; declarations remain byte-identical.",
            "An inert base supplies only IsOpen state and abstract override signatures.",
            "PowerProfile/FanProfile are data-only shells; no HC constructors are executed.",
            "AsusACPI.SetFanCurve is an in-memory recorder and returns a documented synthetic integer.",
        ],
        "ranges": ranges,
    }
    return result, (json.dumps(metadata, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[4])
    parser.add_argument("--check", action="store_true", help="Read-only check of pinned sources and generated artifacts")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    source, metadata = build(args.repo_root.resolve())
    outputs = [(root / "Generated/HcRogSourceOracle.g.cs", source),
               (root / "HcRogSourceOracle.provenance.json", metadata)]
    for path, content in outputs:
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise ValueError(f"Generated artifact is missing or stale: {path}; regenerate explicitly")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"HC pinned extraction {'verified' if args.check else 'generated'}: {len(SELECTIONS)} verbatim declarations; ROG SHA256={PINS[ROG]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())