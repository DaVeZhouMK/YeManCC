// Immutable source identity registration only; no provider or live root authorization.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const json=file=>JSON.parse(fs.readFileSync(file,'utf8').replace(/^\uFEFF/,''));
const q=JSON.stringify;
const prefix='HandheldCompanion.Devices.OneXPlayer';
function keys(value,expected,code) {
 if(!value||typeof value!=='object'||Array.isArray(value)||
    JSON.stringify(Object.keys(value).sort())!==JSON.stringify([...expected].sort()))throw Error(code);
}
export function buildOneXVirtualControllerArtifacts({repo,catalog,policy}) {
 policy??=json(path.join(repo,'capabilities/hc-onex-virtual-controller-policy.json'));
 catalog??=json(path.join(repo,'capabilities/hc-device-catalog.json'));
 keys(policy,['schemaVersion','scope','legacyCatalog','registrations'],'ONEX_VIRTUAL_POLICY_FIELDS');
 if(policy.schemaVersion!==1||policy.scope!=='immutable-OneX-source-identity-only'||
    policy.legacyCatalog!=='capabilities/hc-device-catalog.generated.h'||
    !Array.isArray(policy.registrations)||policy.registrations.length!==3||!Array.isArray(catalog.devices))
  throw Error('ONEX_VIRTUAL_POLICY_SCOPE');
 // The existing exact DMI resolver supplies class identity. Motion/lighting
 // providers and the HC binary factory table grant no registration authority.
 const resolver=fs.readFileSync(path.join(repo,'capabilities/HcOemInputCapabilityBinding.h'),'utf8');
 const begin=resolver.indexOf('inline constexpr std::string_view resolveOneXDeviceClass(');
 const end=resolver.indexOf('// Only immutable model/profile/catalog selection',begin);
 if(begin<0||end<begin)throw Error('ONEX_VIRTUAL_IDENTITY_RESOLVER');
 const resolverClasses=new Set([...resolver.slice(begin,end).matchAll(/"(HandheldCompanion\.Devices\.OneXPlayer[A-Za-z0-9]+)"/g)].map(m=>m[1]));
 const ids=new Set(),classes=new Set();
 const rows=policy.registrations.map(row=>{
  keys(row,['deviceId','canonicalClass','sourceFile','sourceSha256','sourcePin'],'ONEX_VIRTUAL_REGISTRATION_FIELDS');
  const cls=row.canonicalClass;
  if(typeof cls!=='string'||!cls.startsWith(prefix)||cls.length<=prefix.length||
     !resolverClasses.has(cls)||classes.has(cls))throw Error('ONEX_VIRTUAL_REVIEWED_CLASS');
  const name=cls.slice('HandheldCompanion.Devices.'.length);
  if(!/^[A-Za-z0-9]+$/.test(name)||row.deviceId!=='ymcc.device.'+name||ids.has(row.deviceId)||
     !/^[a-f0-9]{40}$/.test(row.sourcePin)||!/^[a-f0-9]{64}$/.test(row.sourceSha256)||
     row.sourceFile!==`capabilities/upstream/${row.sourcePin.slice(0,8)}/${name}.cs`)
   throw Error('ONEX_VIRTUAL_SOURCE_IDENTITY');
  // A source-only row must never stand in for a frozen DLL factory class/alias.
  if(catalog.devices.some(d=>d.deviceId===row.deviceId||d.consumerClass===cls||
     d.sourceType===cls||d.runtimeType===cls||d.aliases?.includes(cls)))
   throw Error('ONEX_VIRTUAL_FROZEN_IDENTITY_COLLISION');
  const bytes=fs.readFileSync(path.join(repo,row.sourceFile));
  if(sha(bytes)!==row.sourceSha256)throw Error('ONEX_VIRTUAL_SOURCE_SHA:'+row.sourceFile);
  const text=bytes.toString('utf8');
  if(!/namespace\s+HandheldCompanion\.Devices\s*[;{]/.test(text)||
     !new RegExp('\\bclass\\s+'+name+'\\s*:\\s*[A-Za-z0-9_.]+').test(text))
   throw Error('ONEX_VIRTUAL_SOURCE_CLASS:'+name);
  ids.add(row.deviceId);classes.add(cls);
  return {...row,registrationKind:'reviewed-source-only'};
 });
 const metadata={schemaVersion:1,scope:policy.scope,legacyCatalog:policy.legacyCatalog,
  registeredSourceIdentities:rows.length,rows,
  authority:'immutable-class-identity-only;live-internal-root-topology-source-and-Host-owner-remain-runtime-owned'};
 metadata.catalogSha256=sha(JSON.stringify(metadata));
 const header=[
  '// Generated by tools/lib/hc_onex_virtual_controller_catalog.mjs; source-only identities, not HC DLL factory entries.',
  '#pragma once','#include <array>','#include <string_view>',
  'namespace ymcc::capabilities::onexVirtual {',
  'struct SourceIdentity { std::string_view deviceId, canonicalClass, sourceFile, sourceSha256, sourcePin; };',
  'inline constexpr std::string_view sourceIdentityCatalogSha256 = '+q(metadata.catalogSha256)+';',
  'inline constexpr std::array<SourceIdentity, '+rows.length+'> reviewedSourceIdentities = {{',
  ...rows.map(row=>'    {'+[row.deviceId,row.canonicalClass,row.sourceFile,row.sourceSha256,row.sourcePin].map(q).join(', ')+'},'),
  '}};','} // namespace ymcc::capabilities::onexVirtual',''
 ].join('\n');
 return {metadata,artifacts:{'capabilities/HcOneXVirtualControllerCapability.generated.h':header}};
}
